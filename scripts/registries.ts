import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

function files(directory: URL, suffix: string): string[] {
  return readdirSync(directory)
    .filter((file) => file.endsWith(suffix))
    .sort();
}

function writeChanged(target: URL, text: string): void {
  let current: string | undefined;
  try {
    current = readFileSync(target, 'utf8');
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error;
  }
  if (text !== current) writeFileSync(target, text);
}

/** Static imports keep the rules usable in Vite, Vitest, and plain Node alike. */
export function generateRegistries(root = new URL('../', import.meta.url)): void {
  const saves = new URL('src/sim/save-changes/', root);
  const changes = files(saves, '.json').map((file) => {
    if (!/^[a-z][a-z0-9-]*\.json$/.test(file))
      throw new Error(`invalid save change filename: ${file}`);
    const data: unknown = JSON.parse(readFileSync(new URL(file, saves), 'utf8'));
    if (
      typeof data !== 'object' ||
      data === null ||
      !('adds' in data) ||
      typeof data.adds !== 'string' ||
      !data.adds.trim()
    ) {
      throw new Error(`${file} must describe what it adds`);
    }
    return { name: file.slice(0, -5), adds: data.adds };
  });
  if (!changes.length) throw new Error('the save format must contain at least one change');
  writeChanged(
    new URL('src/sim/save-changes.generated.json', root),
    JSON.stringify(changes, null, 2) + '\n',
  );

  const alerts = new URL('src/app/alert-kinds/', root);
  const kinds: string[] = [];
  for (const file of files(alerts, '.json')) {
    const data: unknown = JSON.parse(readFileSync(new URL(file, alerts), 'utf8'));
    if (
      !Array.isArray(data) ||
      !data.length ||
      !data.every(
        (kind): kind is string => typeof kind === 'string' && /^[a-z][a-zA-Z0-9]*$/.test(kind),
      )
    ) {
      throw new Error(`${file} must contain nonempty alert-kind names`);
    }
    kinds.push(...data);
  }
  if (!kinds.length || new Set(kinds).size !== kinds.length)
    throw new Error('alert kinds must be nonempty and unique');
  const header = '// Generated by scripts/registries.ts; do not edit.\n';
  writeChanged(
    new URL('src/app/alert-kinds.generated.ts', root),
    `${header}export const ALERT_KINDS = [\n${kinds.map((kind) => `  '${kind}',`).join('\n')}\n] as const;\n`,
  );

  const orders = files(new URL('src/sim/orders/registrations/', root), '.ts');
  if (!orders.length) throw new Error('the order registry must not be empty');
  for (const file of orders) {
    if (!/^[a-z][a-z0-9-]*\.ts$/.test(file))
      throw new Error(`invalid order registration filename: ${file}`);
  }
  const imports = orders
    .map((file, i) => `import r${i} from './registrations/${file}';`)
    .join('\n');
  const handlers = orders.map((_, i) => `  [r${i}.kind]: r${i}.handler,`).join('\n');
  const slots = orders.map((_, i) => `  [r${i}.kind]: r${i}.slot,`).join('\n');
  const unique = `const kinds = [\n${orders.map((_, i) => `  r${i}.kind,`).join('\n')}\n];\nif (new Set(kinds).size !== kinds.length) throw new Error('duplicate order kind');\n`;
  writeChanged(
    new URL('src/sim/orders/registry.generated.ts', root),
    `${header}${imports}\n\nexport const ORDER_HANDLERS = {\n${handlers}\n};\n\nexport const ORDER_SLOTS = {\n${slots}\n};\n\n${unique}`,
  );
}

if (import.meta.main) generateRegistries();
